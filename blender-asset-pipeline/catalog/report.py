"""Coverage summary and the static review page for the catalogue gate."""

from __future__ import annotations

import html
from collections import Counter

_CSS = """
:root { --bg:#f4f2ee; --card:#fff; --ink:#24272b; --muted:#6b7078; --line:#e2dfd8; --part:#2f7d4f;
        --composite:#8a5a14; --reference:#5b6470; --warn:#b3261e; }
* { box-sizing:border-box; }
body { margin:0; padding:24px 16px 64px; background:var(--bg); color:var(--ink);
       font:14px/1.45 system-ui, -apple-system, "Segoe UI", sans-serif; }
main { max-width:1280px; margin:0 auto; }
h1 { font-size:22px; margin:0 0 4px; } h2 { font-size:17px; margin:32px 0 8px; }
h3 { font-size:13px; letter-spacing:.06em; color:var(--muted); margin:20px 0 8px; }
.muted { color:var(--muted); }
table { border-collapse:collapse; width:100%; background:var(--card); }
th, td { text-align:left; padding:6px 10px; border-bottom:1px solid var(--line); font-variant-numeric:tabular-nums; }
.grid { display:grid; grid-template-columns:repeat(auto-fill, minmax(190px, 1fr)); gap:10px; }
.card { background:var(--card); border:1px solid var(--line); border-radius:8px; padding:8px; }
.card img { width:100%; height:130px; object-fit:contain; background:#ecebe7; border-radius:4px; }
.noimg { height:130px; display:grid; place-items:center; background:#f6e7e5; color:var(--warn); border-radius:4px; font-size:12px; }
.name { font-weight:600; margin-top:6px; } .meta { font-size:12px; color:var(--muted); }
.ocr { font-size:12px; color:var(--warn); }
.tag { display:inline-block; font-size:11px; padding:1px 6px; border-radius:10px; color:#fff; margin-right:4px; }
.part { background:var(--part); } .composite { background:var(--composite); } .reference { background:var(--reference); }
ul.issues { background:var(--card); padding:12px 28px; border:1px solid var(--line); border-radius:8px; }
code { font-size:12px; }
"""


def _e(value) -> str:
    return html.escape(str(value))


def _card(item: dict, source: dict) -> str:
    img = (f'<img loading="lazy" src="{_e(source["crop"])}" alt="{_e(item["name"])}">'
           if source["crop"] else '<div class="noimg">no object matched</div>')
    ocr = (f'<div class="ocr">OCR read: {_e(source["rawLabel"])}</div>'
           if source["rawLabel"].lower() != item["name"].lower() and source["rawLabel"].upper() != source["rawLabel"] else "")
    dims = _e(item["dimsText"]) if item["dimsText"] else '<span class="muted">no dims printed</span>'
    if item.get("dimsOrigin") == "correction":
        dims += ' <span class="ocr">(from corrections.toml)</span>'
    if source["origin"] == "hand":
        ocr = '<div class="ocr">hand-named: no printed label on the board</div>'
    family = f' · {_e(item["family"])}' if item["family"] else ""
    return (f'<div class="card">{img}<div class="name">{_e(item["name"])}</div>{ocr}'
            f'<div class="meta">{dims}</div>'
            f'<div class="meta"><span class="tag {item["kind"]}">{item["kind"]}</span>{_e(item["category"])}{family}</div>'
            f'<div class="meta"><code>{_e(item["id"])}</code></div></div>')


def write_review_page(path, catalogue: dict, report: dict) -> None:
    items = catalogue["items"]
    kinds = Counter(i["kind"] for i in items)
    families = Counter(i["family"] for i in items if i["family"])

    rows = "".join(
        f'<tr><td>{_e(b["file"])}</td><td>{b["role"]}</td><td>{b["labels"]}</td><td>{b["matched"]}</td>'
        f'<td>{b["handAdded"]}</td>'
        f'<td>{len(report["boards"].get(b["file"], {}).get("issues", []))}</td></tr>'
        for b in catalogue["boards"])
    family_rows = "".join(f"<tr><td>{_e(f)}</td><td>{n}</td></tr>" for f, n in families.most_common())

    by_board: dict[str, dict[str, list[str]]] = {}
    for item in items:
        for source in item["sources"]:
            by_board.setdefault(source["board"], {}).setdefault(source["section"] or "(no section)", []).append(
                _card(item, source))
    board_html = ""
    for board, sections in sorted(by_board.items()):
        board_html += f"<h2>{_e(board)}</h2>"
        for section, cards in sections.items():
            board_html += f'<h3>{_e(section)}</h3><div class="grid">{"".join(cards)}</div>'

    issues = "".join(f"<li><b>{_e(board)}</b>: {_e(msg)}</li>"
                     for board, data in report["boards"].items() for msg in data["issues"])

    page = f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Asset Catalogue Review</title><style>{_CSS}</style></head><body><main>
<h1>Asset catalogue review</h1>
<p class="muted">Generated by <code>python blender-asset-pipeline/run.py catalog</code>. Each card is one label
read from a reference board, the object crop matched to it, and how the pipeline classified it.
Fix names in <code>data/corrections.toml</code> and mappings in <code>data/families.toml</code>, then rerun.</p>
<table><tr><th>Items</th><th>Parts (buildable)</th><th>Composites (layouts)</th><th>Reference only</th><th>Label occurrences</th></tr>
<tr><td>{len(items)}</td><td>{kinds["part"]}</td><td>{kinds["composite"]}</td><td>{kinds["reference"]}</td>
<td>{sum(len(i["sources"]) for i in items)}</td></tr></table>
<h2>Boards</h2><table><tr><th>Board</th><th>Role</th><th>Printed labels</th><th>Matched to an object</th>
<th>Hand-named (no label)</th><th>Issues</th></tr>{rows}</table>
<h2>Parts per builder family</h2><table><tr><th>Family</th><th>Items</th></tr>{family_rows}</table>
<h2>Issues to resolve</h2><ul class="issues">{issues or "<li>None</li>"}</ul>
{board_html}
</main></body></html>"""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(page, encoding="utf-8")
